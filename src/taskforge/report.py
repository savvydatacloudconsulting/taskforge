"""Reports built from the files on disk, so they can be rebuilt any time offline."""

from __future__ import annotations

import html
import json
from pathlib import Path

from . import __version__
from .checker import PROOF_ORDER
from .package import TaskPackage
from .variation import MIN_DISTANCE, batch_score, matrix, signature

PROOF_LABELS = {
    "fails_before": "Fails before", "passes_after": "Passes after",
    "nothing_breaks": "Nothing breaks", "tests_have_teeth": "Tests have teeth",
}


def _json(path: Path):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def load(out_dir: Path) -> dict:
    out = Path(out_dir)
    records, sigs = [], []
    for status in ("accepted", "rejected"):
        base = out / status
        if not base.exists():
            continue
        for d in sorted(p for p in base.iterdir() if p.is_dir()):
            info = _json(d / "validation" / "attempts.json") or {}
            proofs = _json(d / "validation" / "proofs.json") or {}
            by_name = {p["name"]: p for p in proofs.get("proofs", [])}
            teeth = (by_name.get("tests_have_teeth") or {}).get("evidence", {})
            rec = {
                "id": d.name, "status": status, "title": info.get("title", ""), "recipes": info.get("recipes", []),
                "attempts": len(info.get("attempts", [])), "reason": info.get("reason", ""),
                "proofs": {n: by_name.get(n, {}).get("status", "-") for n in PROOF_ORDER},
                "details": {n: by_name.get(n, {}).get("detail", "") for n in PROOF_ORDER},
                "kill_rate": teeth.get("kill_rate"), "mutants": teeth.get("mutants"),
                "nearest_task": info.get("nearest_task"), "nearest_distance": info.get("nearest_distance"),
                "history": info.get("attempts", []),
            }
            records.append(rec)
            if status == "accepted" and (d / "task.toml").exists():
                pkg = TaskPackage.load(d)
                sigs.append(signature(pkg.task_id, pkg.solution_patch, pkg.recipes))
    run = _json(out / "run.json") or {}
    acc = [r for r in records if r["status"] == "accepted"]
    kills = [r["kill_rate"] for r in acc if r["kill_rate"] is not None]
    return {
        "generator": f"taskforge {__version__}", "run": run, "records": records,
        "summary": {
            "total": len(records), "accepted": len(acc), "rejected": len(records) - len(acc),
            "acceptance_rate": round(len(acc) / len(records), 3) if records else None,
            "mean_attempts": round(sum(r["attempts"] for r in records) / len(records), 2) if records else None,
            "mean_kill_rate": round(sum(kills) / len(kills), 3) if kills else None,
            "variation_score": batch_score(sigs),
        },
        "variation": {"ids": [s.task_id for s in sigs], "matrix": matrix(sigs), "min_distance": MIN_DISTANCE},
    }


SYM = {"pass": "PASS", "fail": "FAIL", "skipped": "skip", "-": "-"}


def to_markdown(data: dict) -> str:
    s, run = data["summary"], data["run"]
    L = [f"# TaskForge report", ""]
    if run:
        L.append(f"Repository: `{run.get('repo')}` at `{str(run.get('base_commit', ''))[:10]}` ({run.get('language')})  ")
        ai = run.get("ai", {})
        L.append(f"Generated by {data['generator']} | AI backend: {ai.get('backend')} | AI calls: {ai.get('calls')} "
                 f"(cache hits: {ai.get('cache_hits', 0)}) | seed {run.get('seed')}  ")
        L.append("")
    L += ["## Summary", "",
          f"- Tasks attempted: **{s['total']}**; accepted: **{s['accepted']}**; rejected: **{s['rejected']}**",
          f"- Acceptance rate: **{s['acceptance_rate']:.0%}**" if s["acceptance_rate"] is not None else "- Acceptance rate: n/a",
          f"- Mean attempts per task: {s['mean_attempts']}",
          f"- Mean mutation kill rate of accepted tasks: {s['mean_kill_rate']:.0%}" if s["mean_kill_rate"] is not None else "- Mutation kill rate: n/a",
          f"- Variation score (mean pairwise distance, higher is more varied): {s['variation_score']}", "",
          "## Tasks", "",
          "| Task | Recipes | Status | " + " | ".join(PROOF_LABELS[n] for n in PROOF_ORDER) + " | Kill rate | Attempts |",
          "|---|---|---|" + "---|" * (len(PROOF_ORDER) + 2)]
    for r in data["records"]:
        kr = f"{r['kill_rate']:.0%}" if r["kill_rate"] is not None else "-"
        L.append(f"| {r['id']} | {', '.join(r['recipes'])} | {r['status']} | "
                 + " | ".join(SYM.get(r["proofs"][n], r["proofs"][n]) for n in PROOF_ORDER) + f" | {kr} | {r['attempts']} |")
    rej = [r for r in data["records"] if r["status"] == "rejected"]
    if rej:
        L += ["", "## Rejected tasks and why", ""]
        for r in rej:
            L.append(f"- **{r['id']}**: {r['reason'] or 'see validation/attempts.json'}")
    v = data["variation"]
    if len(v["ids"]) > 1:
        L += ["", f"## Variation (pairwise distance; tasks below {v['min_distance']} would be rejected as near-duplicates)", "",
              "| | " + " | ".join(str(i + 1) for i in range(len(v["ids"]))) + " |", "|---|" + "---|" * len(v["ids"])]
        for i, row in enumerate(v["matrix"]):
            L.append(f"| {i + 1}. {v['ids'][i]} | " + " | ".join("-" if i == j else f"{x:.2f}" for j, x in enumerate(row)) + " |")
    L += ["", "Re-check any task offline (no AI needed):", "",
          "```", "taskforge check <task folder> --repo <path to the repository>", "```", ""]
    return "\n".join(L)


