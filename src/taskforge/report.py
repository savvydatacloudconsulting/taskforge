def to_html(data: dict) -> str:
    e = html.escape
    s, run, v = data["summary"], data["run"], data["variation"]
    pct = lambda x: "n/a" if x is None else f"{x:.0%}"
    cards = [
        (s["total"], "tasks attempted"), (s["accepted"], "accepted"), (s["rejected"], "rejected"),
        (pct(s["acceptance_rate"]), "acceptance rate"), (pct(s["mean_kill_rate"]), "mean mutation kill rate"),
        ("n/a" if s["variation_score"] is None else s["variation_score"], "variation score"),
        ("n/a" if s["mean_attempts"] is None else s["mean_attempts"], "mean attempts / task"),
    ]
    rows = []
    for r in data["records"]:
        cells = "".join(
            f'<td><span class="pill {e(r["proofs"][n])}" title="{e(r["details"][n])}">{e(SYM.get(r["proofs"][n], "-"))}</span></td>'
            for n in PROOF_ORDER)
        kr = pct(r["kill_rate"]) if r["kill_rate"] is not None else "-"
        rows.append(f'<tr><td class="id">{e(r["id"])}<br><small>{e(r["title"])}</small></td><td>{e(", ".join(r["recipes"]))}</td>'
                    f'<td><span class="pill {r["status"]}">{r["status"]}</span></td>{cells}<td>{kr}</td><td>{r["attempts"]}</td></tr>')
    rej = "".join(f'<li><b class="id">{e(r["id"])}</b>: {e(r["reason"] or "see validation/attempts.json")}</li>'
                  for r in data["records"] if r["status"] == "rejected")
    heat = ""
    if len(v["ids"]) > 1:
        head = "".join(f"<th>{i + 1}</th>" for i in range(len(v["ids"])))
        body = ""
        for i, row in enumerate(v["matrix"]):
            tds = ""
            for j, x in enumerate(row):
                if i == j:
                    tds += "<td>-</td>"
                else:
                    a = min(1.0, x)
                    tds += f'<td style="background:rgba(23,110,184,{0.08 + 0.55 * a:.2f})">{x:.2f}</td>'
            body += f'<tr><th class="id">{i + 1}. {e(v["ids"][i])}</th>{tds}</tr>'
        heat = (f"<h2>Variation between accepted tasks</h2><p>Distance 0 means the same shape (only names or numbers differ); "
                f"tasks closer than {v['min_distance']} are rejected as near-duplicates.</p>"
                f'<div class="scroll"><table class="heat"><tr><th></th>{head}</tr>{body}</table></div>')
    ai = run.get("ai", {})
    sub = (f"{e(str(run.get('repo', '')))} @ {e(str(run.get('base_commit', ''))[:10])} | AI backend: {e(str(ai.get('backend', '')))} | "
           f"AI calls: {e(str(ai.get('calls', '')))} | {e(data['generator'])}") if run else e(data["generator"])
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>TaskForge report</title><style>{CSS}</style></head><body>
<header><h1>TaskForge report</h1><p>{sub}</p></header><main>
<div class="cards">{''.join(f'<div class="card"><b>{e(str(a))}</b><span>{e(b)}</span></div>' for a, b in cards)}</div>
<h2>Tasks</h2><div class="scroll"><table><tr><th>Task</th><th>Recipes</th><th>Status</th>
{''.join(f'<th>{PROOF_LABELS[n]}</th>' for n in PROOF_ORDER)}<th>Kill rate</th><th>Attempts</th></tr>{''.join(rows)}</table></div>
{('<h2>Rejected tasks and why</h2><ul>' + rej + '</ul>') if rej else ''}
{heat}
<h2>Re-check offline</h2><p>No AI is needed to verify a task. Run:</p>
<pre>taskforge check &lt;task folder&gt; --repo &lt;path to the repository&gt;</pre>
</main></body></html>"""


def write_reports(out_dir: Path) -> dict[str, Path]:
    data = load(out_dir)
    out = Path(out_dir)
    paths = {"json": out / "report.json", "md": out / "report.md", "html": out / "report.html"}
    paths["json"].write_text(json.dumps(data, indent=2), encoding="utf-8", newline="\n")
    paths["md"].write_text(to_markdown(data), encoding="utf-8", newline="\n")
    paths["html"].write_text(to_html(data), encoding="utf-8", newline="\n")
    return paths
